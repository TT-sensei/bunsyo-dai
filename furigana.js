const escapeHtml = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;');

const dictionaryEntries = Object.entries(readings)
  .sort(([a], [b]) => b.length - a.length);

export function addFurigana(value) {
  const text = String(value ?? '');
  let output = '';
  let index = 0;

  while (index < text.length) {
    const match = dictionaryEntries.find(([word]) => text.startsWith(word, index));
    if (match) {
      const [word, reading] = match;
      output += '<ruby>' + escapeHtml(word) + '<rt>' + escapeHtml(reading) + '</rt></ruby>';
      index += word.length;
    } else {
      output += escapeHtml(text[index]);
      index += 1;
    }
  }
  return output;
}
